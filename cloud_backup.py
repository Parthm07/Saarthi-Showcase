"""Back up the cloud database, and move it to a different Postgres.

Most of what the cloud holds is a PROJECTION of the laptop: items,
customers, rates, reorder lines and six months of history are all
regenerated by `python tally_cloud.py --push`. Losing them costs a push.

The following tables also hold data received directly from the website:

    app_user, user_route    who may sign in, and what they can see
    prospect                shops found in the field
    cloud_order, _line      what salespeople actually ordered
    pending_our_rate       owner edits awaiting a laptop sync

Those exist only here. If Railway loses this database, or the account it
sits in goes away, they are gone -- and with them every rep's order
history. That is what this file is for.

    python cloud_backup.py --dump                 # to cloud_backup/<date>.json.gz
    python cloud_backup.py --restore "postgres://...new..."
    python cloud_backup.py --verify  "postgres://...new..."

The restore refuses to write into a database that already holds data
unless --force is given, so pointing it at the wrong URL cannot quietly
overwrite a live one.
"""
import argparse
import datetime as dt
import decimal
import gzip
import json
import pathlib
import sys
from uuid import UUID

import psycopg

import cloud_db

OUT = cloud_db.HERE / "cloud_backup"

# Parents before children: user_route and prospect reference app_user,
# cloud_order_line references cloud_order, history_line references
# history_voucher. Restoring out of order fails on the foreign keys.
TABLE_ORDER = [
    "app_user", "user_route", "prospect",
    "item", "customer", "party_rate", "party_buy",
    "history_voucher", "history_line",
    "cloud_order", "cloud_order_line", "sync_status", "pending_our_rate",
]

# The ones that cannot be rebuilt from the laptop. Reported separately,
# because "the backup has 47,000 rows" is reassuring and beside the point.
AUTHORITATIVE = {"app_user", "user_route", "prospect",
                 "cloud_order", "cloud_order_line", "pending_our_rate"}


def _plain(v):
    """Postgres types -> JSON. Numbers keep full precision as strings;
    float() would quietly round money."""
    if isinstance(v, decimal.Decimal):
        return str(v)
    if isinstance(v, (dt.datetime, dt.date)):
        return v.isoformat()
    if isinstance(v, UUID):
        return str(v)
    return v


def dump(url=None, path=None, log=print):
    with cloud_db.connect(url) as cx, cx.cursor() as cur:
        data, counts = {}, {}
        for table in TABLE_ORDER:
            if table == 'pending_our_rate' and not cloud_db.pending_our_rates_available(cur):
                continue
            cur.execute(f"SELECT * FROM {table}")
            cols = [d.name for d in cur.description]
            rows = [[_plain(v) for v in r] for r in cur.fetchall()]
            data[table] = {"columns": cols, "rows": rows}
            counts[table] = len(rows)
    payload = {"taken_at": dt.datetime.now().isoformat(timespec="seconds"),
               "tables": data}
    OUT.mkdir(exist_ok=True)
    path = pathlib.Path(path or (
        OUT / f"cloud-{dt.datetime.now():%Y%m%d-%H%M%S}.json.gz"))
    with gzip.open(path, "wt", encoding="utf-8") as f:
        json.dump(payload, f)
    kb = path.stat().st_size / 1024
    log(f"wrote {path.name}  ({kb:,.0f} KB)")
    keep = sum(counts[t] for t in AUTHORITATIVE)
    log(f"  {sum(counts.values()):,} rows, of which {keep} are the ones that "
        f"exist ONLY here:")
    for t in TABLE_ORDER:
        mark = "*" if t in AUTHORITATIVE else " "
        log(f"   {mark} {t:18} {counts[t]:>7}")
    return path, counts


def load(path):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return json.load(f)


def restore(target_url, path=None, force=False, only_authoritative=False,
            log=print):
    """Load a dump into another Postgres. Creates the schema first."""
    path = path or latest()
    if not path:
        raise SystemExit("no backup found -- run --dump first")
    payload = load(path)
    tables = ([t for t in TABLE_ORDER if t in AUTHORITATIVE]
              if only_authoritative else TABLE_ORDER)
    log(f"restoring {path.name} (taken {payload['taken_at']}) into the target")

    with cloud_db.connect(target_url) as cx:
        with cx.cursor() as cur:
            cloud_db.create_schema(cur, log=lambda *a: None)
            # Refuse to write into a database that already holds something,
            # so a mistyped URL cannot overwrite a live one.
            busy = {}
            for t in tables:
                cur.execute(f"SELECT COUNT(*) FROM {t}")
                n = cur.fetchone()[0]
                if n:
                    busy[t] = n
            if busy and not force:
                raise SystemExit(
                    "the target already holds data and --force was not "
                    "given, so nothing was written:\n  "
                    + "\n  ".join(f"{t}: {n} rows" for t, n in busy.items()))
            done = {}
            for t in tables:
                block = payload["tables"].get(t)
                if not block or not block["rows"]:
                    done[t] = 0
                    continue
                cols = block["columns"]
                ph = ",".join(["%s"] * len(cols))
                cur.executemany(
                    f"INSERT INTO {t}({','.join(cols)}) VALUES({ph})"
                    f" ON CONFLICT DO NOTHING", block["rows"])
                done[t] = len(block["rows"])
                log(f"   {t:18} {done[t]:>7}")
        cx.commit()
    log(f"restored {sum(done.values()):,} rows")
    return done


def verify(target_url, path=None, log=print):
    """Compare a dump against a database, table by table."""
    path = path or latest()
    payload = load(path)
    bad = []
    with cloud_db.connect(target_url) as cx, cx.cursor() as cur:
        log(f"{'table':20} {'backup':>8} {'target':>8}")
        for t in TABLE_ORDER:
            want = len(payload["tables"].get(t, {}).get("rows", []))
            if t == 'pending_our_rate' and not cloud_db.pending_our_rates_available(cur):
                if want:
                    bad.append(t)
                continue
            cur.execute(f"SELECT COUNT(*) FROM {t}")
            got = cur.fetchone()[0]
            flag = "" if got == want else "   <-- differs"
            if got != want and t in AUTHORITATIVE:
                bad.append(t)
            log(f"{t:20} {want:>8} {got:>8}{flag}")
    if bad:
        log(f"\nMISMATCH in tables that cannot be rebuilt: {', '.join(bad)}")
    else:
        log("\nevery table that exists only in the cloud matches")
    return not bad


def latest():
    files = sorted(OUT.glob("cloud-*.json.gz")) if OUT.is_dir() else []
    return files[-1] if files else None


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", action="store_true")
    ap.add_argument("--restore", metavar="URL")
    ap.add_argument("--verify", metavar="URL")
    ap.add_argument("--file", help="use this backup instead of the newest")
    ap.add_argument("--force", action="store_true",
                    help="write even though the target already has data")
    ap.add_argument("--only-authoritative", action="store_true",
                    help="restore only what a push cannot rebuild")
    a = ap.parse_args()
    f = pathlib.Path(a.file) if a.file else None
    if a.dump:
        dump(path=f)
    elif a.restore:
        restore(a.restore, path=f, force=a.force,
                only_authoritative=a.only_authoritative)
    elif a.verify:
        verify(a.verify, path=f)
    else:
        ap.print_help()
        sys.exit(1)
